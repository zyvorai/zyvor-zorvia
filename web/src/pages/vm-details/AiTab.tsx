import { useState } from 'react'
import { Loader2, Sparkles } from 'lucide-react'
import type { VM } from '../../api/vm'
import { diagnoseVm, type AiDiagnosis } from '../../api/ai'
import ErrorBanner from '../../components/ErrorBanner'
import { formatUserError } from '../../utils/apiError'

/** On-demand AI diagnosis. Read-only: the model never changes the VM. */
export default function AiTab({ vm }: { vm: VM }) {
  const [result, setResult] = useState<AiDiagnosis | null>(null)
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)

  const run = async () => {
    setLoading(true)
    setError(null)
    try {
      setResult(await diagnoseVm(vm.name))
    } catch (e) {
      setResult(null)
      setError(formatUserError(e))
    } finally {
      setLoading(false)
    }
  }

  return (
    <div className="space-y-4">
      <div className="bg-[var(--zf-canvas)] rounded-xl border border-[var(--zf-hairline)] p-4 space-y-3">
        <p className="text-sm text-[var(--zf-muted)]">
          Sends this VM&apos;s status, events and recent launcher logs, with secrets redacted, to the configured AI provider
          and returns a suggested diagnosis. It cannot change anything; you decide what to do with the suggestions.
        </p>
        <button
          onClick={() => void run()}
          disabled={loading}
          className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-[var(--zf-ink)] text-[var(--zf-canvas)] text-sm disabled:opacity-60"
        >
          {loading ? <Loader2 className="w-3.5 h-3.5 animate-spin" /> : <Sparkles className="w-3.5 h-3.5" />}
          {loading ? 'Analyzing...' : 'Diagnose this VM'}
        </button>
      </div>

      {error && <ErrorBanner title="Diagnosis failed" headline={error} onRetry={() => void run()} />}

      {result && (
        <div className="bg-[var(--zf-canvas)] rounded-xl border border-[var(--zf-hairline)] p-4 space-y-3">
          <div className="text-xs text-[var(--zf-muted)]">AI-generated by {result.model}. Verify before acting.</div>
          <pre className="whitespace-pre-wrap text-sm text-[var(--zf-ink)] font-sans">{result.diagnosis}</pre>
          <details className="text-sm">
            <summary className="cursor-pointer text-[var(--zf-muted)]">Evidence sent to the provider</summary>
            <pre className="mt-2 overflow-x-auto text-xs text-[var(--zf-muted)]">
              {JSON.stringify(result.evidence_sent, null, 2)}
            </pre>
          </details>
        </div>
      )}
    </div>
  )
}
